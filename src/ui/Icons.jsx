import { cloneElement, useId } from "react";

export const Icon = ({
                         children,
                         size = 20,
                         variant = "solid", // solid | muted | gradient
                         className,
                         colors = ["#0074cc"]
                     }) => {
    const gradientId = useId();

    // colors && colors.length === 0 ? colors = "#FFFFFF" : "#CCCCCC";
    // colors = colors || ["#55F69D", "#67D6FF"];

    const style =
        variant === "gradient"
            ? { stroke: `url(#${gradientId})`, fill: `transparent`}
            : { stroke: colors[0], fill: `transparent`};

    return (
        <svg viewBox="0 0 24 24"
             className={`icon icon--${variant} ${className || ""}`}
             width={size}
             height={size}
        >
            {variant === "gradient" && (
                <defs>
                    <linearGradient
                        id={gradientId}
                        x1="0%"
                        y1="0%"
                        x2="100%"
                        y2="100%"
                    >
                        <stop offset="0%" stopColor={colors[0]} />
                        <stop offset="100%" stopColor={colors[1]} />
                    </linearGradient>
                </defs>
            )}
            {cloneElement(children, { style })}
        </svg>

    );
};


